#!/usr/bin/env python3
"""Downloads DB-IP's "IP to Country Lite" database and normalizes it into the committed static
snapshot backend/app/geo/data/country_ranges.tsv.gz (consumed by app.geo.lookup), then
regenerates backend/app/geo/data/sources.md.

Run manually, locally, whenever you want to refresh the bundled data. It is NOT part of any
deploy/build/CI step (same convention as scripts/refresh_threat_intel.py). Analysis never
makes a network call. The snapshot is static, point-in-time data and goes stale as address
space is reassigned; country-level only, since city-level IP geolocation is unreliable.

License: DB-IP's Lite databases are published under Creative Commons Attribution 4.0
International (CC BY 4.0). Commercial use and redistribution are allowed with attribution
to DB-IP.com. The UI shows "IP geolocation by DB-IP" wherever a resolved country is
displayed. Before writing anything, this script checks that the download page still states
CC BY 4.0 and refuses to proceed if it doesn't. If DB-IP ever changes terms, the app falls
back to showing raw IPs with "location unknown" (a missing snapshot is not an error).

Snapshot format (gzipped TSV, contiguous ranges, one row per range start):
    # snapshot: YYYY-MM
    4<TAB><start delta from previous IPv4 start, decimal><TAB><ISO 3166-1 alpha-2 | ZZ>
    6<TAB><start delta from previous IPv6 start, decimal><TAB><code>
Each range ends where the next one of the same family starts (DB-IP's data has no gaps, and
this script verifies that). Delta encoding keeps the committed file small.

Usage:
    python3 scripts/refresh_geoip.py                       # download current month
    python3 scripts/refresh_geoip.py --from-file X.csv.gz  # normalize an already-downloaded file
                                                           # (license page is still checked)
"""

from __future__ import annotations

import argparse
import csv
import gzip
import io
import ipaddress
import re
import sys
import urllib.request
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
DATA_DIR = REPO_ROOT / "backend" / "app" / "geo" / "data"
OUT_PATH = DATA_DIR / "country_ranges.tsv.gz"
SOURCES_PATH = DATA_DIR / "sources.md"

LICENSE_PAGE_URL = "https://db-ip.com/db/download/ip-to-country-lite"
USER_AGENT = "cordon-geoip-refresh/0.1 (defensive-security; contact via GitHub)"
_DOWNLOAD_RE = re.compile(r"https://download\.db-ip\.com/free/dbip-country-lite-(\d{4}-\d{2})\.csv\.gz")


def _fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=120) as resp:
        return resp.read()


def _check_license(page_html: str) -> None:
    if "Creative Commons Attribution 4.0 International" not in page_html:
        sys.exit(
            "ABORT: DB-IP's download page no longer states CC BY 4.0. Do not bundle this "
            "data until the license has been re-reviewed. The app will show raw IPs with "
            "'location unknown' without a snapshot."
        )


def _normalize(raw_gz: bytes) -> tuple[list[str], dict[int, int]]:
    rows: list[str] = []
    counts = {4: 0, 6: 0}
    prev_start = {4: 0, 6: 0}
    prev_end: dict[int, int | None] = {4: None, 6: None}
    with gzip.open(io.BytesIO(raw_gz), "rt", encoding="utf-8") as fh:
        for record in csv.reader(fh):
            if len(record) != 3:
                continue
            start_s, end_s, code = record
            start = ipaddress.ip_address(start_s)
            end = ipaddress.ip_address(end_s)
            fam = start.version
            s, e = int(start), int(end)
            if prev_end[fam] is not None and s != prev_end[fam] + 1:
                sys.exit(f"ABORT: gap/overlap in IPv{fam} ranges before {start_s}; format changed?")
            code = code.strip().upper()
            if not re.fullmatch(r"[A-Z]{2}", code):
                code = "ZZ"
            rows.append(f"{fam}\t{s - prev_start[fam]}\t{code}")
            prev_start[fam] = s
            prev_end[fam] = e
            counts[fam] += 1
    return rows, counts


def _write_sources_md(snapshot: str, counts: dict[int, int]) -> None:
    SOURCES_PATH.write_text(
        f"""# IP geolocation data source

Regenerated by `scripts/refresh_geoip.py`, snapshot **{snapshot}** (fetched {date.today().isoformat()}).

## DB-IP IP to Country Lite

- Source: <{LICENSE_PAGE_URL}>
- License: **Creative Commons Attribution 4.0 International (CC BY 4.0)**, verified on the
  download page at fetch time. Commercial use and redistribution are permitted with
  attribution to DB-IP.com.
- Attribution: the UI shows "IP geolocation by DB-IP" (linking to https://db-ip.com) wherever
  a resolved country is displayed. This file is the attribution for the bundled data.
- Granularity: **country only**. City-level IP geolocation is unreliable and isn't bundled.
- Ranges this snapshot: {counts[4]} IPv4, {counts[6]} IPv6
- Consumed by `app.geo.lookup`. Purely offline; no lookup ever leaves the server.

A missing or unreadable snapshot degrades to "location unknown" for every IP. It never
guesses a country.
""",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--from-file", type=Path, help="already-downloaded dbip-country-lite-*.csv.gz")
    args = parser.parse_args()

    print("Checking DB-IP license page...")
    page = _fetch(LICENSE_PAGE_URL).decode("utf-8", errors="replace")
    _check_license(page)
    print("  CC BY 4.0 confirmed")

    if args.from_file:
        raw = args.from_file.read_bytes()
        m = re.search(r"(\d{4}-\d{2})", args.from_file.name)
        snapshot = m.group(1) if m else date.today().strftime("%Y-%m")
    else:
        m = _DOWNLOAD_RE.search(page)
        if not m:
            sys.exit("ABORT: couldn't find the download link on DB-IP's page.")
        snapshot = m.group(1)
        print(f"Downloading {m.group(0)} ...")
        raw = _fetch(m.group(0))

    rows, counts = _normalize(raw)
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    body = f"# snapshot: {snapshot}\n# source: DB-IP IP to Country Lite (CC BY 4.0), https://db-ip.com\n"
    body += "\n".join(rows) + "\n"
    with gzip.open(OUT_PATH, "wt", encoding="utf-8", compresslevel=9) as fh:
        fh.write(body)
    _write_sources_md(snapshot, counts)
    print(f"Wrote {OUT_PATH} ({OUT_PATH.stat().st_size:,} bytes): {counts[4]} IPv4, {counts[6]} IPv6 ranges")


if __name__ == "__main__":
    main()
