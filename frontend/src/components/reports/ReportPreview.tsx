import type { SecurityComplianceReportDetail } from "../../types/analysis";

interface ReportPreviewProps {
  report: SecurityComplianceReportDetail;
  onDownload: (format: "pdf" | "json") => void;
  isDownloading: boolean;
}

function StatCard({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-xl border border-slate-200 bg-white p-5 shadow-sm">
      <p className="text-sm font-medium text-slate-500">{label}</p>
      <p className="mt-1 text-3xl font-bold text-slate-900">{value}</p>
    </div>
  );
}

export default function ReportPreview({ report, onDownload, isDownloading }: ReportPreviewProps) {
  const period = `${new Date(report.period_start).toLocaleDateString()} – ${new Date(
    report.period_end
  ).toLocaleDateString()}`;

  return (
    <div className="flex flex-col gap-6">
      <div className="flex flex-wrap items-start justify-between gap-4 rounded-xl border border-slate-200 bg-white p-6 shadow-sm">
        <div>
          <h2 className="text-lg font-semibold text-slate-900">{report.account_name}</h2>
          <p className="text-sm text-slate-500">
            Security &amp; Compliance Report &middot; {period}
          </p>
          <p className="mt-1 text-xs text-slate-400">
            Generated {new Date(report.created_at).toLocaleString()}
          </p>
        </div>
        <div className="flex gap-2">
          <button
            onClick={() => onDownload("pdf")}
            disabled={isDownloading}
            className="rounded-lg bg-indigo-600 px-4 py-2 text-sm font-semibold text-white shadow-sm transition hover:bg-indigo-500 disabled:cursor-not-allowed disabled:bg-slate-300"
          >
            {isDownloading ? "Preparing…" : "Download PDF"}
          </button>
          <button
            onClick={() => onDownload("json")}
            disabled={isDownloading}
            className="rounded-lg border border-slate-300 px-4 py-2 text-sm font-semibold text-slate-700 transition hover:bg-slate-50 disabled:cursor-not-allowed disabled:text-slate-300"
          >
            JSON
          </button>
        </div>
      </div>

      <div className="rounded-xl border border-slate-200 bg-white p-6 shadow-sm">
        <h3 className="text-sm font-semibold uppercase tracking-wide text-slate-500">
          Executive Summary
        </h3>
        <p className="mt-3 text-base leading-relaxed text-slate-800">
          {report.executive_summary.text}
        </p>
        <p className="mt-3 text-xs text-slate-400">
          {report.executive_summary.source === "llm"
            ? "Generated by Cordon's AI analyst, grounded only in the figures below."
            : "Generated directly from the figures below (no AI narrative layer)."}
        </p>
      </div>

      {!report.has_any_activity ? (
        <div className="rounded-xl border border-amber-200 bg-amber-50 p-6 text-sm text-amber-800">
          No email analysis, intrusion detections, early-warning alerts, or phishing-simulation
          activity was recorded for this account in this period.
        </div>
      ) : (
        <>
          <div className="grid grid-cols-1 gap-4 sm:grid-cols-4">
            <StatCard label="Emails Analyzed" value={String(report.emails_analyzed)} />
            <StatCard label="Threats Detected" value={String(report.threats_detected)} />
            <StatCard label="Threats Contained" value={String(report.threats_contained)} />
            <StatCard
              label="Exposure Avoided"
              value={`$${report.exposure_avoided_usd.toLocaleString(undefined, {
                maximumFractionDigits: 0,
              })}`}
            />
          </div>

          <div className="rounded-xl border border-slate-200 bg-white p-6 shadow-sm">
            <h3 className="text-sm font-semibold uppercase tracking-wide text-slate-500">
              Verdict Breakdown
            </h3>
            <div className="mt-3 grid grid-cols-3 gap-4 text-center">
              <div>
                <p className="text-2xl font-bold text-red-600">{report.verdict_breakdown.malicious}</p>
                <p className="text-xs text-slate-500">Malicious</p>
              </div>
              <div>
                <p className="text-2xl font-bold text-amber-600">{report.verdict_breakdown.suspicious}</p>
                <p className="text-xs text-slate-500">Suspicious</p>
              </div>
              <div>
                <p className="text-2xl font-bold text-emerald-600">{report.verdict_breakdown.safe}</p>
                <p className="text-xs text-slate-500">Safe</p>
              </div>
            </div>
          </div>

          <div className="rounded-xl border border-slate-200 bg-white p-6 shadow-sm">
            <h3 className="text-sm font-semibold uppercase tracking-wide text-slate-500">
              Intrusion &amp; Early Warning
            </h3>
            <p className="mt-3 text-sm text-slate-700">
              {report.incidents_detected} intrusion/data-exfiltration incident(s) detected.{" "}
              {report.early_warning_alerts_raised} early-warning alert(s) raised.
            </p>
          </div>

          <div className="rounded-xl border border-slate-200 bg-white p-6 shadow-sm">
            <h3 className="text-sm font-semibold uppercase tracking-wide text-slate-500">
              Human Risk / Phishing Simulation
            </h3>
            {report.human_risk.campaigns_run > 0 ? (
              <p className="mt-3 text-sm text-slate-700">
                {report.human_risk.campaigns_run} campaign(s) run against{" "}
                {report.human_risk.employees_tested} employee(s).{" "}
                {report.human_risk.employees_clicked} clicked the simulated lure,{" "}
                {report.human_risk.employees_reported} reported it, and{" "}
                {report.human_risk.employees_flagged_for_training} were flagged for follow-up
                training.
              </p>
            ) : (
              <p className="mt-3 text-sm text-slate-500">
                No phishing-simulation campaigns were run in this period.
              </p>
            )}
          </div>

          <div className="overflow-hidden rounded-xl border border-slate-200 bg-white shadow-sm">
            <div className="border-b border-slate-200 bg-slate-900 px-6 py-3">
              <h3 className="text-base font-semibold text-white">Control-Framework Coverage</h3>
            </div>
            <table className="w-full text-left text-sm">
              <thead className="border-b border-slate-200 bg-slate-50 text-xs uppercase tracking-wide text-slate-500">
                <tr>
                  <th className="px-6 py-3 font-medium">Framework</th>
                  <th className="px-6 py-3 font-medium">Controls Covered</th>
                  <th className="px-6 py-3 font-medium">Coverage</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {report.framework_coverage.map((row) => (
                  <tr key={row.framework_key}>
                    <td className="px-6 py-3 text-slate-800">{row.framework_name}</td>
                    <td className="px-6 py-3 text-slate-600">
                      {row.covered_controls} / {row.total_controls}
                    </td>
                    <td className="px-6 py-3 text-slate-600">{row.coverage_pct}%</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </>
      )}
    </div>
  );
}
