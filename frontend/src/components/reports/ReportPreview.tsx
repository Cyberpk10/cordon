import type { SecurityComplianceReportDetail } from "../../types/analysis";

interface ReportPreviewProps {
  report: SecurityComplianceReportDetail;
  onDownload: (format: "pdf" | "json") => void;
  isDownloading: boolean;
}

function StatCard({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-xl border border-line bg-surface-card p-5 shadow-sm">
      <p className="text-sm font-semibold text-fg-secondary">{label}</p>
      <p className="mt-1 text-3xl font-semibold text-fg">{value}</p>
    </div>
  );
}

export default function ReportPreview({ report, onDownload, isDownloading }: ReportPreviewProps) {
  const period = `${new Date(report.period_start).toLocaleDateString()} – ${new Date(
    report.period_end
  ).toLocaleDateString()}`;

  return (
    <div className="flex flex-col gap-6">
      <div className="flex flex-wrap items-start justify-between gap-4 rounded-xl border border-line bg-surface-card p-6 shadow-sm">
        <div>
          <h2 className="text-lg font-semibold text-fg">{report.account_name}</h2>
          <p className="text-sm text-fg-secondary">
            Security &amp; Compliance Report &middot; {period}
          </p>
          <p className="mt-1 text-xs text-fg-muted">
            Generated {new Date(report.created_at).toLocaleString()}
          </p>
        </div>
        <div className="flex gap-2">
          <button
            onClick={() => onDownload("pdf")}
            disabled={isDownloading}
            className="rounded-lg bg-accent px-4 py-2 text-sm font-semibold text-fg shadow-sm transition hover:bg-accent-hover disabled:cursor-not-allowed disabled:bg-line-strong"
          >
            {isDownloading ? "Preparing…" : "Download PDF"}
          </button>
          <button
            onClick={() => onDownload("json")}
            disabled={isDownloading}
            className="rounded-lg border border-line-strong px-4 py-2 text-sm font-semibold text-fg transition hover:bg-surface-raised disabled:cursor-not-allowed disabled:text-fg-muted"
          >
            JSON
          </button>
        </div>
      </div>

      <div className="rounded-xl border border-line bg-surface-card p-6 shadow-sm">
        <h3 className="text-sm font-semibold uppercase tracking-wide text-fg-secondary">
          Executive Summary
        </h3>
        <p className="mt-3 text-base leading-relaxed text-fg">
          {report.executive_summary.text}
        </p>
        <p className="mt-3 text-xs text-fg-muted">
          {report.executive_summary.source === "llm"
            ? "Generated by Cordon's AI analyst, grounded only in the figures below."
            : "Generated directly from the figures below (no AI narrative layer)."}
        </p>
      </div>

      {!report.has_any_activity ? (
        <div className="rounded-xl border border-warning/25 bg-warning/10 p-6 text-sm text-warning">
          No email analysis, intrusion detections, early-warning alerts, or phishing-simulation
          activity was recorded for this account in this period.
        </div>
      ) : (
        <>
          <div className="grid grid-cols-1 gap-4 sm:grid-cols-4">
            <StatCard label="Emails Analyzed" value={String(report.emails_analyzed)} />
            <StatCard label="Threats Detected" value={String(report.threats_detected)} />
            <StatCard label="Threats Contained" value={String(report.threats_contained)} />
            <StatCard
              label="Exposure Avoided"
              value={`$${report.exposure_avoided_usd.toLocaleString(undefined, {
                maximumFractionDigits: 0,
              })}`}
            />
          </div>

          <div className="rounded-xl border border-line bg-surface-card p-6 shadow-sm">
            <h3 className="text-sm font-semibold uppercase tracking-wide text-fg-secondary">
              Verdict Breakdown
            </h3>
            <div className="mt-3 grid grid-cols-3 gap-4 text-center">
              <div>
                <p className="text-2xl font-semibold text-danger">{report.verdict_breakdown.malicious}</p>
                <p className="text-xs text-fg-secondary">Malicious</p>
              </div>
              <div>
                <p className="text-2xl font-semibold text-warning">{report.verdict_breakdown.suspicious}</p>
                <p className="text-xs text-fg-secondary">Suspicious</p>
              </div>
              <div>
                <p className="text-2xl font-semibold text-success">{report.verdict_breakdown.safe}</p>
                <p className="text-xs text-fg-secondary">Safe</p>
              </div>
            </div>
          </div>

          <div className="rounded-xl border border-line bg-surface-card p-6 shadow-sm">
            <h3 className="text-sm font-semibold uppercase tracking-wide text-fg-secondary">
              Intrusion &amp; Early Warning
            </h3>
            <p className="mt-3 text-sm text-fg">
              {report.incidents_detected} intrusion/data-exfiltration incident(s) detected.{" "}
              {report.early_warning_alerts_raised} early-warning alert(s) raised.
            </p>
          </div>

          <div className="rounded-xl border border-line bg-surface-card p-6 shadow-sm">
            <h3 className="text-sm font-semibold uppercase tracking-wide text-fg-secondary">
              Human Risk / Phishing Simulation
            </h3>
            {report.human_risk.campaigns_run > 0 ? (
              <p className="mt-3 text-sm text-fg">
                {report.human_risk.campaigns_run} campaign(s) run against{" "}
                {report.human_risk.employees_tested} employee(s).{" "}
                {report.human_risk.employees_clicked} clicked the simulated lure,{" "}
                {report.human_risk.employees_reported} reported it, and{" "}
                {report.human_risk.employees_flagged_for_training} were flagged for follow-up
                training.
              </p>
            ) : (
              <p className="mt-3 text-sm text-fg-secondary">
                No phishing-simulation campaigns were run in this period.
              </p>
            )}
          </div>

          <div className="overflow-hidden rounded-xl border border-line bg-surface-card shadow-sm">
            <div className="border-b border-line bg-surface-panel px-6 py-3">
              <h3 className="text-base font-semibold text-fg">Control-Framework Coverage</h3>
            </div>
            <table className="w-full text-left text-sm">
              <thead className="border-b border-line bg-surface-panel text-xs uppercase tracking-wide text-fg-secondary">
                <tr>
                  <th className="px-6 py-3 font-semibold">Framework</th>
                  <th className="px-6 py-3 font-semibold">Controls Covered</th>
                  <th className="px-6 py-3 font-semibold">Coverage</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-line">
                {report.framework_coverage.map((row) => (
                  <tr key={row.framework_key}>
                    <td className="px-6 py-3 text-fg">{row.framework_name}</td>
                    <td className="px-6 py-3 text-fg-secondary">
                      {row.covered_controls} / {row.total_controls}
                    </td>
                    <td className="px-6 py-3 text-fg-secondary">{row.coverage_pct}%</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </>
      )}
    </div>
  );
}
